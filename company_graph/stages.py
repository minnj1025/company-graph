"""업종코드(KSIC) → 가치사슬 단계. 화면에서 점을 묶고 색을 정하는 데 쓴다. 규칙으로만 정한다 (DESIGN.md 12장 13번)."""
import re

# 앞에서부터 맞는 것을 쓴다
_RULES = [
    (("301", "302"), "완성차"),
    (("303", "304"), "자동차 부품"),
    (("20", "22", "23", "24", "25"), "소재"),
    (("26", "27", "28"), "전자·전기"),
    (("29", "31"), "기계·운송장비"),
    (("45", "46", "47", "49", "50", "51", "52"), "물류·판매"),
    (("58", "59", "60", "61", "62", "63"), "IT·콘텐츠"),
    (("64", "65", "66"), "금융"),
    (("41", "42"), "건설"),
]


def stage(induty_code: str | None) -> str:
    # 공정위 자료의 업종코드는 "L6811"처럼 대분류 글자가 앞에 붙는다
    code = re.sub(r"^[A-Z]", "", induty_code or "")
    for prefixes, name in _RULES:
        if code.startswith(prefixes):
            return name
    return "기타"
