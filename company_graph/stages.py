"""업종코드(KSIC) → 가치사슬 단계. 화면에서 점을 묶고 색을 정하는 데 쓴다. 규칙으로만 정한다 (DESIGN.md 12장 13번)."""
import re

# 앞에서부터 맞는 것을 쓴다
_RULES = [
    (("301", "302"), "완성차"),
    (("303", "304"), "자동차 부품"),
    (("20", "22", "23", "24", "25"), "소재"),
    (("26", "27", "28"), "전자·전기"),
    (("29", "31"), "기계·운송장비"),
    (("45", "46", "47", "49", "50", "51", "52"), "물류·판매"),
    (("58", "59", "60", "61", "62", "63"), "IT·콘텐츠"),
    (("64", "65", "66"), "금융"),
    (("41", "42"), "건설"),
]


def stage(induty_code: str | None) -> str:
    # 공정위 자료의 업종코드는 "L6811"처럼 대분류 글자가 앞에 붙는다
    code = re.sub(r"^[A-Z]", "", induty_code or "")
    for prefixes, name in _RULES:
        if code.startswith(prefixes):
            return name
    return "기타"


# 전체 상장사를 묶는 업종. 한국표준산업분류(KSIC) 중분류(앞 두 자리)를 스무 개 남짓으로 모은다
_SECTORS = [
    (("01", "02", "03", "05", "06", "07", "08"), "농림어업·광업"),
    (("10", "11", "12"), "식품·음료"),
    (("13", "14", "15"), "섬유·의류"),
    (("16", "17", "18"), "목재·종이·인쇄"),
    (("19", "20"), "화학·석유"),
    (("21",), "의약품"),
    (("22", "23"), "고무·플라스틱·비금속"),
    (("24", "25"), "금속"),
    (("26",), "전자부품·통신장비"),
    (("27",), "의료·정밀기기"),
    (("28",), "전기장비"),
    (("29",), "기계"),
    (("30",), "자동차"),
    (("31",), "조선·항공·철도"),
    (("32", "33", "34"), "기타 제조"),
    (("35", "36", "37", "38", "39"), "전기·가스·환경"),
    (("41", "42"), "건설"),
    (("45", "46", "47"), "도소매"),
    (("49", "50", "51", "52"), "운수·물류"),
    (("58", "59", "60", "61", "62", "63"), "IT·콘텐츠"),
    (("64", "65", "66"), "금융"),
    (("68",), "부동산"),
    (("70", "71", "72", "73"), "전문·과학기술"),
]


def sector(induty_code: str | None) -> str:
    code = re.sub(r"^[A-Z]", "", induty_code or "")
    if not code:
        return "업종 정보 없음"
    for prefixes, name in _SECTORS:
        if code.startswith(prefixes):
            return name
    return "기타 서비스"
